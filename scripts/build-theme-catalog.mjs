import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { parseArgs } from "node:util";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const { values } = parseArgs({
  options: {
    "theme-root": { type: "string", default: resolve(scriptDir, "../../writex-theme-packs/themes") },
    output: { type: "string", default: resolve(scriptDir, "../src/themeCatalog.generated.ts") },
    repo: { type: "string", default: "pakco77/writex-theme-packs" },
    tag: { type: "string", default: "v0.6.1-themes.1" },
  },
});

const themeRoot = resolve(values["theme-root"]);
const outputPath = resolve(values.output);
const repo = values.repo;
const tag = values.tag;
const ids = ["zen", "moyu-green", "red-white", "graphite", "ticket", "olive", "cyberpunk"];

if (!/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(repo)) throw new Error(`Invalid GitHub repository: ${repo}`);
if (!/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(tag)) throw new Error(`Invalid release tag: ${tag}`);

const packageFiles = (await readdir(themeRoot))
  .filter(name => name.endsWith(".writex-theme.json"))
  .sort();
const expectedFiles = ids.map(id => `${id}.writex-theme.json`).sort();
if (JSON.stringify(packageFiles) !== JSON.stringify(expectedFiles)) {
  throw new Error(`Theme file set mismatch. Expected ${expectedFiles.join(", ")}; found ${packageFiles.join(", ")}`);
}

const quote = value => JSON.stringify(String(value));
const rows = [];
for (const id of ids) {
  const filename = `${id}.writex-theme.json`;
  const bytes = await readFile(resolve(themeRoot, filename));
  let theme;
  try {
    theme = JSON.parse(bytes.toString("utf8"));
  } catch (error) {
    throw new Error(`${filename} is not valid JSON: ${error instanceof Error ? error.message : String(error)}`);
  }
  const manifest = theme?.manifest;
  if (!manifest || manifest.id !== id) throw new Error(`${filename} manifest ID must be ${id}`);
  for (const key of ["name", "version", "author", "license", "sourceUrl", "minWriteXVersion"]) {
    if (typeof manifest[key] !== "string" || !manifest[key]) throw new Error(`${filename} is missing manifest.${key}`);
  }

  const downloadUrl = `https://github.com/${repo}/releases/download/${tag}/${filename}`;
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  rows.push(
    `  { id: ${quote(id)}, name: ${quote(manifest.name)}, version: ${quote(manifest.version)}, delivery: "download", defaultInstalled: ${id === "zen"}, downloadUrl: ${quote(downloadUrl)}, sha256: ${quote(sha256)}, byteLength: ${bytes.byteLength}, author: ${quote(manifest.author)}, license: ${quote(manifest.license)}, sourceUrl: ${quote(manifest.sourceUrl)}, minWriteXVersion: ${quote(manifest.minWriteXVersion)} },`,
  );
}

const source = [
  'import type { ThemeCatalogEntry } from "./themeCatalog.ts";',
  "",
  `// Generated by scripts/build-theme-catalog.mjs for ${repo}@${tag}. Do not edit by hand.`,
  "export const GENERATED_THEME_CATALOG: readonly ThemeCatalogEntry[] = [",
  ...rows,
  "];",
  "",
].join("\n");

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source);
console.log(`Wrote ${ids.length} pinned theme entries to ${outputPath}`);
